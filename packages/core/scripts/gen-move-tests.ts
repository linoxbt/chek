/**
 * Generates move/chek/tests/merkle_vectors_tests.move from fixtures/vectors.json, so the Move
 * package is checked against the same bytes as TypeScript and Rust.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { REPO_ROOT, VECTORS_PATH, writeOrCheck } from "./vectors-lib.ts";

interface LeafCase {
  i: number;
  author_id: string;
  address: string;
  hash: string;
}
interface TreeCase {
  n: number;
  root: string;
  proofs: string[][];
}

interface PayloadCase {
  name: string;
  payload: Record<string, string | number | boolean>;
  payload_bcs: string;
  signature: string;
}

const v = JSON.parse(readFileSync(VECTORS_PATH, "utf8")) as {
  leaves: LeafCase[];
  trees: TreeCase[];
  enclave_test_key: { public_key: string };
  snapshot_payloads: PayloadCase[];
};
const seq = v.leaves.slice(3);
const tree = (n: number) => {
  const t = v.trees.find((t) => t.n === n);
  if (!t) throw new Error(`no tree with n = ${n}`);
  return t;
};
const proofLit = (p: string[]) => `vector[${p.map((h) => `x"${h}"`).join(", ")}]`;
const leafArgs = (l: LeafCase) => `${l.i}u32, ${l.author_id}u64, @${l.address}`;

const lines: string[] = [];
lines.push(
  "// Generated by packages/core/scripts/gen-move-tests.ts from fixtures/vectors.json. Do not edit;",
  "// run `pnpm vectors` instead.",
  "#[test_only]",
  "module chek::merkle_vectors_tests;",
  "",
  "use chek::merkle;",
  "",
  "#[test]",
  "fun leaf_hashes_match_vectors() {",
);
for (const l of v.leaves.slice(0, 11)) lines.push(`    assert!(merkle::leaf_hash(${leafArgs(l)}) == x"${l.hash}");`);
lines.push("}", "");

for (const n of [1, 2, 3, 5, 13]) {
  const t = tree(n);
  lines.push("#[test]", `fun proofs_verify_n${n}() {`, `    let root = x"${t.root}";`);
  for (let i = 0; i < n; i++) {
    lines.push(`    assert!(merkle::verify(&root, ${leafArgs(seq[i]!)}, &${proofLit(t.proofs[i]!)}));`);
  }
  lines.push("}", "");
}

const t13 = tree(13);
const l5 = seq[5]!;
const p5 = t13.proofs[5]!;
const tampered = p5.map((h, k) => (k === 1 ? (parseInt(h.slice(0, 2), 16) ^ 1).toString(16).padStart(2, "0") + h.slice(2) : h));
lines.push(
  "#[test]",
  "fun bad_proofs_are_rejected() {",
  `    let root = x"${t13.root}";`,
  `    // Proof for leaf 5 offered for index 4, and leaf 5 with leaf 4's proof.`,
  `    assert!(!merkle::verify(&root, 4u32, ${l5.author_id}u64, @${l5.address}, &${proofLit(p5)}));`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit(t13.proofs[4]!)}));`,
  `    // Changed author, changed address.`,
  `    assert!(!merkle::verify(&root, 5u32, 1u64, @${l5.address}, &${proofLit(p5)}));`,
  `    assert!(!merkle::verify(&root, 5u32, ${l5.author_id}u64, @${seq[6]!.address}, &${proofLit(p5)}));`,
  `    // Index beyond the tree whose low bits match (5 + 16).`,
  `    assert!(!merkle::verify(&root, 21u32, ${l5.author_id}u64, @${l5.address}, &${proofLit(p5)}));`,
  `    // Tampered, shortened and lengthened proofs; a sibling of the wrong length.`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit(tampered)}));`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit(p5.slice(0, -1))}));`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit([...p5, p5[0]!])}));`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit([p5[0]!.slice(0, 62), ...p5.slice(1)])}));`,
  "}",
  "",
);

writeOrCheck(resolve(REPO_ROOT, "move/chek/tests/merkle_vectors_tests.move"), lines.join("\n"));

// --- Entrant fixtures for campaign tests: roots, leaves and proofs of the vector trees. ---

const HEADER = [
  "// Generated by packages/core/scripts/gen-move-tests.ts from fixtures/vectors.json. Do not edit;",
  "// run `pnpm vectors` instead.",
];
const FIXTURE_SIZES = [0, 1, 2, 3, 5, 13];
const ent: string[] = [...HEADER, "#[test_only]", "module chek::test_entrants;", ""];
ent.push("/// Merkle root of the first n vector leaves.", "public fun root(n: u64): vector<u8> {");
for (const n of FIXTURE_SIZES) ent.push(`    if (n == ${n}) return x"${tree(n).root}";`);
ent.push("    abort 0", "}", "");
const fixtureLeaves = seq.slice(0, 13);
ent.push("public fun author(i: u32): u64 {", `    let all = vector[${fixtureLeaves.map((l) => `${l.author_id}u64`).join(", ")}];`, "    all[i as u64]", "}", "");
ent.push("public fun addr(i: u32): address {", `    let all = vector[${fixtureLeaves.map((l) => `@${l.address}`).join(", ")}];`, "    all[i as u64]", "}", "");
ent.push("/// Proof of leaf i in the tree of the first n vector leaves.", "public fun proof(n: u64, i: u32): vector<vector<u8>> {");
for (const n of FIXTURE_SIZES.filter((n) => n > 0)) {
  ent.push(`    if (n == ${n}) {`, `        let all = vector[${tree(n).proofs.map(proofLit).join(", ")}];`, "        return all[i as u64]", "    };");
}
ent.push("    abort 0", "}", "");
writeOrCheck(resolve(REPO_ROOT, "move/chek/tests/test_entrants.move"), ent.join("\n"));

// --- Signed snapshot payloads: BCS layout and Ed25519 verification through Nautilus. ---

const P = v.snapshot_payloads;
const payloadExpr = (p: Record<string, string | number | boolean>, overrides: Record<string, string> = {}) => {
  const f = (k: string, lit: string) => overrides[k] ?? lit;
  return [
    `snapshot::new(`,
    `        object::id_from_address(@${p.campaign_id}),`,
    `        ${f("post_id", `${p.post_id}u64`)},`,
    `        x"${p.rules_hash}",`,
    `        ${p.opened_at}u64,`,
    `        ${p.closes_at}u64,`,
    `        ${p.mode}u8,`,
    `        ${p.k}u16,`,
    `        ${p.max_entrants}u32,`,
    `        ${p.max_judged}u32,`,
    `        ${p.max_replies_read}u32,`,
    `        ${p.fetched_at}u64,`,
    `        ${f("n", `${p.n}u32`)},`,
    `        ${p.replies_seen}u32,`,
    `        x"${p.root}",`,
    `        x"${p.snapshot_hash}",`,
    `        ${p.linked},`,
    `        ${p.post_author_id}u64,`,
    `        ${p.request_counter}u64,`,
    `    )`,
  ].join("\n");
};

const snap: string[] = [
  ...HEADER,
  "#[test_only]",
  "module chek::snapshot_vectors_tests;",
  "",
  "use chek::enclave_app::CHEK;",
  "use chek::snapshot;",
  "use enclave::enclave;",
  "",
  `const TEST_PK: vector<u8> = x"${v.enclave_test_key.public_key}";`,
  "",
];
P.forEach((c, idx) => {
  snap.push(
    `// ${c.name}`,
    "#[test]",
    `fun payload_${idx}_bcs_and_signature() {`,
    "    let mut ctx = tx_context::dummy();",
    "    let e = enclave::new_enclave_for_testing<CHEK>(TEST_PK, &mut ctx);",
    `    let payload = ${payloadExpr(c.payload)};`,
    `    assert!(std::bcs::to_bytes(&payload) == x"${c.payload_bcs}");`,
    `    let sig = x"${c.signature}";`,
    "    assert!(snapshot::verify_signature(&e, &payload, &sig));",
    `    let tampered = ${payloadExpr(c.payload, { n: `${Number(c.payload.n) + 1}u32` })};`,
    "    assert!(!snapshot::verify_signature(&e, &tampered, &sig));",
    `    let other_post = ${payloadExpr(c.payload, { post_id: `${BigInt(String(c.payload.post_id)) + 1n}u64` })};`,
    "    assert!(!snapshot::verify_signature(&e, &other_post, &sig));",
    "    e.destroy();",
    "}",
    "",
  );
});
writeOrCheck(resolve(REPO_ROOT, "move/chek/tests/snapshot_vectors_tests.move"), snap.join("\n"));
