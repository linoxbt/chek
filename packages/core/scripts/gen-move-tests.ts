/**
 * Generates move/chek/tests/merkle_vectors_tests.move from fixtures/vectors.json, so the Move
 * package is checked against the same bytes as TypeScript and Rust.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { REPO_ROOT, VECTORS_PATH, writeOrCheck } from "./vectors-lib.ts";

interface LeafCase {
  i: number;
  author_id: string;
  address: string;
  hash: string;
}
interface TreeCase {
  n: number;
  root: string;
  proofs: string[][];
}

const v = JSON.parse(readFileSync(VECTORS_PATH, "utf8")) as { leaves: LeafCase[]; trees: TreeCase[] };
const seq = v.leaves.slice(3);
const tree = (n: number) => {
  const t = v.trees.find((t) => t.n === n);
  if (!t) throw new Error(`no tree with n = ${n}`);
  return t;
};
const proofLit = (p: string[]) => `vector[${p.map((h) => `x"${h}"`).join(", ")}]`;
const leafArgs = (l: LeafCase) => `${l.i}u32, ${l.author_id}u64, @${l.address}`;

const lines: string[] = [];
lines.push(
  "// Generated by packages/core/scripts/gen-move-tests.ts from fixtures/vectors.json. Do not edit;",
  "// run `pnpm vectors` instead.",
  "#[test_only]",
  "module chek::merkle_vectors_tests;",
  "",
  "use chek::merkle;",
  "",
  "#[test]",
  "fun leaf_hashes_match_vectors() {",
);
for (const l of v.leaves.slice(0, 11)) lines.push(`    assert!(merkle::leaf_hash(${leafArgs(l)}) == x"${l.hash}");`);
lines.push("}", "");

for (const n of [1, 2, 3, 5, 13]) {
  const t = tree(n);
  lines.push("#[test]", `fun proofs_verify_n${n}() {`, `    let root = x"${t.root}";`);
  for (let i = 0; i < n; i++) {
    lines.push(`    assert!(merkle::verify(&root, ${leafArgs(seq[i]!)}, &${proofLit(t.proofs[i]!)}));`);
  }
  lines.push("}", "");
}

const t13 = tree(13);
const l5 = seq[5]!;
const p5 = t13.proofs[5]!;
const tampered = p5.map((h, k) => (k === 1 ? (parseInt(h.slice(0, 2), 16) ^ 1).toString(16).padStart(2, "0") + h.slice(2) : h));
lines.push(
  "#[test]",
  "fun bad_proofs_are_rejected() {",
  `    let root = x"${t13.root}";`,
  `    // Proof for leaf 5 offered for index 4, and leaf 5 with leaf 4's proof.`,
  `    assert!(!merkle::verify(&root, 4u32, ${l5.author_id}u64, @${l5.address}, &${proofLit(p5)}));`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit(t13.proofs[4]!)}));`,
  `    // Changed author, changed address.`,
  `    assert!(!merkle::verify(&root, 5u32, 1u64, @${l5.address}, &${proofLit(p5)}));`,
  `    assert!(!merkle::verify(&root, 5u32, ${l5.author_id}u64, @${seq[6]!.address}, &${proofLit(p5)}));`,
  `    // Index beyond the tree whose low bits match (5 + 16).`,
  `    assert!(!merkle::verify(&root, 21u32, ${l5.author_id}u64, @${l5.address}, &${proofLit(p5)}));`,
  `    // Tampered, shortened and lengthened proofs; a sibling of the wrong length.`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit(tampered)}));`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit(p5.slice(0, -1))}));`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit([...p5, p5[0]!])}));`,
  `    assert!(!merkle::verify(&root, ${leafArgs(l5)}, &${proofLit([p5[0]!.slice(0, 62), ...p5.slice(1)])}));`,
  "}",
  "",
);

writeOrCheck(resolve(REPO_ROOT, "move/chek/tests/merkle_vectors_tests.move"), lines.join("\n"));
